ORG 0

INICIO:
    CALL SORTEAR_PALAVRA
    CALL EXIBIR_PALAVRA
    HLT

SORTEAR_PALAVRA:
    LDI SEMENTE
    TRAP 7
CALCULA_RESTO:
    SUB 20
    JN PEGA_RESTO
    JMP CALCULA_RESTO
PEGA_RESTO:
    ADD 20
    RET

EXIBIR_PALAVRA:
    TRAP 4 STR_VELHA       
    RET

ORG 600h

